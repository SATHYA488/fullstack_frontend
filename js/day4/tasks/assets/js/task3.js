let mark=85;

if (mark>=90 && mark<=100) {
    console.log("A+");

} else if (mark>=75 && mark<=89) {
    console.log("A");
    
} else if (mark>=50 && mark<=74) {
    console.log("B");

} else if (mark>=35 && mark<=49) {
    console.log("C");

} else if (mark<=35) {
       console.log("fail");
} else {
    console.log("invalid");
}