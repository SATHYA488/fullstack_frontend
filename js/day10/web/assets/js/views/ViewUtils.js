  formatCurrency(val) {
    return new Intl.NumberFormat('en-US', { style: 'currency', currency: 'USD' }).format(val);
  },

  formatBadge(status) {
    let cls = 'badge-neutral';
    const s = String(status).toLowerCase();
    if (s === 'active' || s === 'completed' || s === 'operational' || s === 'paid' || s === 'resolved') {
      cls = 'badge-success';
    } else if (s === 'in progress' || s === 'assigned' || s === 'pending' || s === 'in review') {
      cls = 'badge-info';
    } else if (s === 'on leave' || s === 'maintenance' || s === 'medium' || s === 'low') {
      cls = 'badge-warning';
    } else if (s === 'critical' || s === 'high' || s === 'failed' || s === 'overdue') {
      cls = 'badge-danger';
    }
    return `<span class="badge ${cls}">${status}</span>`;
  },

  showToast(message, type = 'info') {
    let container = document.getElementById('toastContainer');
    if (!container) {
      container = document.createElement('div');
      container.id = 'toastContainer';
      container.className = 'toast-container';
      document.body.appendChild(container);
    }

    const toast = document.createElement('div');
    toast.className = 'toast';
    toast.innerHTML = `<span>[System Notification]</span> <strong>${this.escapeHTML(message)}</strong>`;
    container.appendChild(toast);

    setTimeout(() => {
      if (toast.parentNode) toast.parentNode.removeChild(toast);
    }, 3000);
  },

  escapeHTML(str) {
    return String(str)
      .replace(/&/g, '&amp;')
      .replace(/</g, '&lt;')
      .replace(/>/g, '&gt;')
      .replace(/"/g, '&quot;');
  }
